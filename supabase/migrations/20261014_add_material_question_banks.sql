-- Generated banks are deliberately separate from the existing curated
-- question_banks table. Existing MCQ, fill-in-the-blank and theory banks must
-- never be overwritten or mixed with generated questions.
create table if not exists public.material_question_banks (
  id bigint generated by default as identity primary key,
  material_id bigint not null references public.materials(id) on delete cascade,
  course_code text not null,
  question_type text not null check (question_type in ('mcq', 'german', 'theory')),
  questions jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending', 'generating', 'review', 'approved', 'failed')),
  target_count integer not null default 100 check (target_count between 1 and 500),
  generation_provider text,
  validation_provider text,
  last_error text,
  generated_at timestamptz,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (material_id, question_type)
);

create index if not exists material_question_banks_course_type_status_idx
  on public.material_question_banks (course_code, question_type, status);

alter table public.material_question_banks enable row level security;

drop policy if exists "Public can read approved material question banks" on public.material_question_banks;
create policy "Public can read approved material question banks"
  on public.material_question_banks
  for select
  using (status = 'approved');

create or replace function public.set_material_question_bank_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_material_question_bank_updated_at on public.material_question_banks;
create trigger set_material_question_bank_updated_at
  before update on public.material_question_banks
  for each row execute function public.set_material_question_bank_updated_at();
