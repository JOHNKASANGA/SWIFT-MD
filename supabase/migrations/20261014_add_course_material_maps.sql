-- A question bank may only be generated after Swift has shown which parts of
-- a material actually belong to a course. This is deliberately separate from
-- both the source material and the final question bank.
create table if not exists public.course_material_maps (
  id bigint generated by default as identity primary key,
  course_code text not null references public.course_outlines(course_code) on delete cascade,
  material_id bigint not null references public.materials(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'mapping', 'review', 'approved', 'failed')),
  source_text_length integer not null default 0,
  total_chunks integer not null default 0,
  processed_chunks integer not null default 0,
  relevant_units jsonb not null default '[]'::jsonb,
  ignored_units jsonb not null default '[]'::jsonb,
  coverage_plan jsonb not null default '[]'::jsonb,
  target_question_count integer not null default 100
    check (target_question_count between 1 and 500),
  mapping_provider text,
  last_error text,
  mapped_at timestamptz,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (course_code, material_id)
);

create index if not exists course_material_maps_course_status_idx
  on public.course_material_maps (course_code, status);

alter table public.course_material_maps enable row level security;

drop policy if exists "Public can read approved course material maps" on public.course_material_maps;
create policy "Public can read approved course material maps"
  on public.course_material_maps
  for select
  using (status = 'approved');

create or replace function public.set_course_material_map_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_course_material_map_updated_at on public.course_material_maps;
create trigger set_course_material_map_updated_at
  before update on public.course_material_maps
  for each row execute function public.set_course_material_map_updated_at();
