-- Course-outline banks are separate from protected curated banks and from
-- per-material banks. Generation can therefore resume without overwriting
-- questions that already exist.
create table if not exists public.course_content_question_banks (
  id bigint generated by default as identity primary key,
  course_code text not null references public.course_outlines(course_code) on delete cascade,
  question_type text not null check (question_type in ('mcq', 'german', 'theory')),
  questions jsonb not null default '[]'::jsonb,
  target_count integer not null default 100 check (target_count between 1 and 100),
  status text not null default 'generating' check (status in ('generating', 'approved', 'failed')),
  generation_provider text,
  validation_provider text,
  last_error text,
  generated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (course_code, question_type)
);

create index if not exists course_content_banks_course_type_status_idx
  on public.course_content_question_banks (course_code, question_type, status);

alter table public.course_content_question_banks enable row level security;

drop policy if exists "Public can read approved course content banks"
  on public.course_content_question_banks;
create policy "Public can read approved course content banks"
  on public.course_content_question_banks
  for select
  to anon, authenticated
  using (status = 'approved');

create or replace function public.set_course_content_bank_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_course_content_bank_updated_at
  on public.course_content_question_banks;
create trigger set_course_content_bank_updated_at
  before update on public.course_content_question_banks
  for each row execute function public.set_course_content_bank_updated_at();
