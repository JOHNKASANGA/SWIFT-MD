-- Track bounded source extraction separately from question generation.  This
-- lets Swift resume long PDFs page by page and send scanned pages to OCR
-- instead of treating a timed-out request as an empty document.
create table if not exists public.material_extractions (
  id bigint generated by default as identity primary key,
  material_id bigint not null unique references public.materials(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'extracting', 'needs_ocr', 'complete', 'failed')),
  file_type text,
  total_pages integer not null default 0,
  processed_pages integer not null default 0,
  extracted_characters integer not null default 0,
  scanned_pages jsonb not null default '[]'::jsonb,
  last_error text,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (processed_pages >= 0),
  check (total_pages >= 0),
  check (extracted_characters >= 0)
);

create index if not exists material_extractions_status_idx
  on public.material_extractions (status, updated_at);

alter table public.material_extractions enable row level security;

create or replace function public.set_material_extraction_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_material_extraction_updated_at on public.material_extractions;
create trigger set_material_extraction_updated_at
  before update on public.material_extractions
  for each row execute function public.set_material_extraction_updated_at();
